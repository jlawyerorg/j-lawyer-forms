    private void toggleInsolvenz() {
        txtInsolvenzDetails.setEnabled(chkInsolvenz.isSelected());
    }

    private static boolean isEmpty(String s) {
        return s == null || s.trim().length() == 0;
    }

    private static String comboValue(JComboBox cmb) {
        Object item = cmb.getSelectedItem();
        return item == null ? "" : item.toString();
    }

    private float parseBetrag(String s) {
        if (isEmpty(s)) {
            return 0f;
        }
        try {
            String cleaned = s.replace("€", "").replace("EUR", "").replace("Euro", "").trim();
            return betragFormat.parse(cleaned).floatValue();
        } catch (Throwable t) {
            return 0f;
        }
    }

    // Kennzahlen im Übersichtsblock neu berechnen
    public void updateUebersicht() {
        int vertraege = 0;
        int vertraegeAktiv = 0;
        for (int i = 0; i < ANZAHL_VERTRAEGE; i++) {
            if (!isEmpty(vtrPartner.get(i).getText())) {
                vertraege++;
                if (isEmpty(vtrErledigt.get(i).getText())) {
                    vertraegeAktiv++;
                }
            }
        }

        int zstOffen = 0;
        float summeOffen = 0f;
        for (int i = 0; i < ANZAHL_ZAHLUNGSSTOERUNGEN; i++) {
            boolean belegt = !isEmpty(zstGlaeubiger.get(i).getText()) || !isEmpty(zstAktenzeichen.get(i).getText());
            if (belegt && !"erledigt".equals(comboValue(zstStatus.get(i)))) {
                zstOffen++;
                summeOffen += parseBetrag(zstBetrag.get(i).getText());
            }
        }

        int anfragen = 0;
        for (int i = 0; i < ANZAHL_ANFRAGEN; i++) {
            if (!isEmpty(anfAnfragender.get(i).getText())) {
                anfragen++;
            }
        }

        lblAnzVertraege.setText("" + vertraege);
        lblAnzVertraegeAktiv.setText("" + vertraegeAktiv);
        lblAnzZahlungsstoerungen.setText("" + zstOffen);
        lblSummeOffen.setText(String.format(Locale.GERMANY, "%,.2f €", summeOffen));
        lblSchuldnerverzeichnis.setText(chkSchuldnerverzeichnis.isSelected() ? "ja" : "nein");
        lblAnzAnfragen.setText("" + anfragen);
    }

